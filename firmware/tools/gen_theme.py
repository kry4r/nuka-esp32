"""Generate firmware and Web tokens from SPEC §6.6.1–6.6.2."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HEADER = ROOT / "firmware/components/ui/theme_tokens.h"
CSS = ROOT / "hub/src/nuka_hub/web/theme.css"


def luminance(color: str) -> float:
    channels = [int(color[i : i + 2], 16) / 255 for i in (1, 3, 5)]
    linear = [
        c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4 for c in channels
    ]
    return sum(
        c * weight for c, weight in zip(linear, (0.2126, 0.7152, 0.0722), strict=True)
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--theme", type=Path, default=ROOT / "design/theme.json")
    parser.add_argument(
        "--check", action="store_true", help="Check committed outputs without writing"
    )
    args = parser.parse_args()
    theme = json.loads(args.theme.read_text(encoding="utf-8"))
    failed = False
    for foreground, minimum in (("text", 7), ("text_dim", 4.5)):
        for background in ("bg", "surface"):
            low, high = sorted(
                (
                    luminance(theme["color"][foreground]),
                    luminance(theme["color"][background]),
                )
            )
            ratio = (high + 0.05) / (low + 0.05)
            print(f"{foreground}/{background}: {ratio:.2f}:1 (minimum {minimum}:1)")
            failed |= ratio < minimum
    if failed:
        print("Theme contrast requirement failed; no outputs written.")
        return 1

    header = [
        "// SPDX-License-Identifier: AGPL-3.0-or-later",
        "// Generated by firmware/tools/gen_theme.py from design/theme.json.",
        "#ifndef NUKA_THEME_TOKENS_H",
        "#define NUKA_THEME_TOKENS_H",
        "",
    ]
    css = [
        "/* SPDX-License-Identifier: AGPL-3.0-or-later */",
        "/* Generated by firmware/tools/gen_theme.py from design/theme.json. */",
        ":root {",
    ]
    for group in ("color", "radius", "space", "font_size"):
        for name, value in theme[group].items():
            c_value = f"0x{value[1:]}u" if group == "color" else str(value)
            css_value = value if group == "color" else f"{value}px"
            header.append(f"#define NUKA_{group.upper()}_{name.upper()} {c_value}")
            css.append(
                f"  --{group.replace('_', '-')}-{name.replace('_', '-')}: {css_value};"
            )
    header.extend((f"#define NUKA_SAFE_INSET {theme['safe_inset']}", "", "#endif", ""))
    css.extend((f"  --safe-inset: {theme['safe_inset']}px;", "}", ""))
    for path, content in ((HEADER, "\n".join(header)), (CSS, "\n".join(css))):
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                print(
                    f"{path.relative_to(ROOT).as_posix()}: missing or stale; run gen_theme.py"
                )
                failed = True
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    return int(failed)


if __name__ == "__main__":
    raise SystemExit(main())
