"""Generate matching Chinese/English string tables for FW-27."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "firmware/components/assets/strings.inc"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    tables = [
        json.loads((ROOT / f"i18n/strings.{lang}.json").read_text(encoding="utf-8"))
        for lang in ("en", "zh-CN")
    ]
    if tables[0].keys() != tables[1].keys():
        raise SystemExit("Translation keys differ between en and zh-CN")
    lines = [
        "// SPDX-License-Identifier: AGPL-3.0-or-later",
        "// Generated by gen_strings.py.",
    ]
    for key in sorted(tables[0]):
        values = (key, tables[0][key], tables[1][key])
        lines.append(
            "{"
            + ", ".join(json.dumps(value, ensure_ascii=False) for value in values)
            + "},"
        )
    generated = "\n".join(lines) + "\n"
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != generated:
            raise SystemExit("Generated translations are stale")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(generated, encoding="utf-8")
    print(f"Translations: {len(tables[0])} matching keys")


if __name__ == "__main__":
    main()
